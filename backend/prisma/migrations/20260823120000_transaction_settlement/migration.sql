-- 정산 거래를 추가한다. **중단하고 남은 돈이 상점 주인에게 갈 때** 쓴다.
--
-- REFUND와 섞지 않는 이유: 환불은 낸 사람에게 돌아가는 돈이고, 이것은 아무도
-- 가져가지 않은 나머지가 상점으로 가는 돈이다. 둘을 한 타입으로 적으면
-- 「누가 얼마를 돌려받았나」를 거래 내역만 보고는 답할 수 없다.
--
-- PRIZE와도 다르다. 상금은 프라이즈풀의 분배율이 정하는 돈인데, 이 돈은
-- 분배율 밖에 남은 것이다.
--
-- ALTER TYPE ... ADD VALUE는 PostgreSQL 12부터 트랜잭션 안에서 돌 수 있다.
-- 추가한 값을 같은 트랜잭션에서 쓸 수는 없지만, 이 마이그레이션은 값을
-- 쓰지 않으므로 걸리지 않는다.
ALTER TYPE "TransactionType" ADD VALUE 'SETTLEMENT';
